/*
 * Raise every CocoaPods target to the app's own iOS deployment target.
 *
 * Xcode 27 turned "deployment target is below the supported range" from a
 * warning into a hard error, and its floor is iOS 15. Fifteen pod targets —
 * mostly the `*_Privacy` resource bundles of Firebase's transitive
 * dependencies (gRPC, BoringSSL, nanopb, abseil, leveldb, Promises), plus
 * SDWebImage, RNSVG and AsyncStorage — still declare 9.0–12.4 in their
 * podspecs, so the build fails before compiling a line.
 *
 * `react_native_post_install` only lifts the targets React Native owns, and
 * expo-build-properties' `ios.deploymentTarget` only sets the app target, so
 * neither reaches these. `ios/` is generated by prebuild and gitignored, so
 * the fix has to be a config plugin rather than an edit to the Podfile.
 *
 * It only ever raises a target, never lowers one, and resolves the floor from
 * the Podfile's own `platform :ios` line so there is no second number to keep
 * in step with React Native's minimum.
 */
const { withPodfile } = require("expo/config-plugins");

const MARKER = "# withMinPodDeploymentTarget";

const SNIPPET = `
    ${MARKER}
    min_ios_target = Gem::Version.new(installer.podfile.target_definition_list.map { |t| t.platform }.compact.select { |p| p.name == :ios }.map { |p| p.deployment_target.to_s }.max || '15.1')
    installer.generated_projects.flat_map(&:targets).each do |target|
      target.build_configurations.each do |build_config|
        current = build_config.build_settings['IPHONEOS_DEPLOYMENT_TARGET']
        next if current.nil?
        if Gem::Version.new(current.to_s) < min_ios_target
          build_config.build_settings['IPHONEOS_DEPLOYMENT_TARGET'] = min_ios_target.to_s
        end
      end
    end
`;

module.exports = function withMinPodDeploymentTarget(config) {
	return withPodfile(config, (config) => {
		const contents = config.modResults.contents;
		if (contents.includes(MARKER)) return config;

		const anchor = /post_install do \|installer\|\n/;
		if (!anchor.test(contents)) {
			throw new Error(
				"withMinPodDeploymentTarget: no `post_install do |installer|` block in the Podfile — the Expo template changed and this plugin needs updating.",
			);
		}
		config.modResults.contents = contents.replace(
			anchor,
			(match) => match + SNIPPET,
		);
		return config;
	});
};
