const NAMES = [...new Set([...FROM_APP, ...FOR_PORTAL])].sort();

/** Everything between <svg …> and </svg>, verbatim. */
function innerSvg(name) {
	const raw = readFileSync(resolve(SVG_DIR, `${name}.svg`), "utf8");
	const match = raw.match(/<svg[^>]*>([\s\S]*)<\/svg>/);
	if (!match) throw new Error(`Could not parse ${name}.svg`);
	return match[1].replace(/\s+/g, " ").replace(/> </g, "><").trim();
}

const missing = [];
const entries = [];

for (const name of NAMES) {
	try {
		entries.push([name, innerSvg(name)]);
	} catch {
		missing.push(name);
	}
}

if (missing.length) {
	console.error(
		`Not found in the ionicons package:\n  ${missing.join("\n  ")}`,
	);
	process.exit(1);
}

const body = entries
	.map(([name, svg]) => `\t"${name}": '${svg.replace(/'/g, "\\'")}',`)
	.join("\n");

const output = `/*
 * GENERATED by scripts/build-icons.mjs — do not edit by hand.
 *
 * Inner SVG markup for the Ionicons the portal uses, on the set's native
 * 512x512 grid. Regenerate with: node scripts/build-icons.mjs
 */

export const ICONS: Record<string, string> = {
${body}
};

export type IconName = keyof typeof ICONS;
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, output);
console.log(`Wrote ${entries.length} icons to ${OUT}`);
