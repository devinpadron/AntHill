/*
 * Vendors the Ionicons the portal uses into a single TypeScript module.
 *
 * The mobile app renders Ionicons from a TTF via @expo/vector-icons. A font is
 * the wrong shape for the web here — it would mean shipping a 200KB typeface to
 * draw forty glyphs — so the SVG source of the SAME icon set is inlined instead.
 * Same artwork, same visual language, no runtime dependency.
 *
 * The `ionicons` package is a devDependency: this script reads from it at build
 * time and the generated module is committed, so a production install does not
 * need it.
 *
 *   node scripts/build-icons.mjs
 *
 * Icon names come from two places: every glyph the app currently references
 * (grep `name="..."` under src/components, src/screens, src/navigation), plus
 * the desktop-only additions the portal needs — sorting, filtering, exporting,
 * the sidebar.
 */

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const SVG_DIR = resolve(here, "../node_modules/ionicons/dist/svg");
const OUT = resolve(here, "../src/ui/icons.generated.ts");

